    var window: UIWindow?

    func application(_ application: UIApplication, didFinishLaunchingWithOptions launchOptions: [UIApplication.LaunchOptionsKey: Any]?) -> Bool {
        // The pi-web shell flow (settings/load/error — see
        // mobile/docs/spike-remote-bridge.md and PiWebViewController) is owned
        // by the root view controller, instantiated from Main.storyboard. If
        // the storyboard linkage is ever bypassed (e.g. a template regression
        // strips the customClass), fall back to building it programmatically
        // so the shell never boots into a vanilla Capacitor webview that
        // ignores the stored server URL.
        if window == nil {
            let mainWindow = UIWindow(frame: UIScreen.main.bounds)
            mainWindow.rootViewController = PiWebViewController()
            mainWindow.makeKeyAndVisible()
            window = mainWindow
        } else if !(window?.rootViewController is PiWebViewController) {
            window?.rootViewController = PiWebViewController()
        }
        return true
    }

