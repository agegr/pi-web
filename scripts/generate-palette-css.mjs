#!/usr/bin/env node
/**
 * Generate app/palettes.css from the single source of truth in
 * lib/theme-palettes.ts.
 *
 *   node scripts/generate-palette-css.mjs
 *
 * Emits a `html[data-palette="X"]` block (dark fallback) and a
 * `html:not(.dark)[data-palette="X"]` block (light) for every non-`pi`
 * palette. The `pi` palette is the default and lives in globals.css
 * (:root = light, html.dark = dark), so it needs no data-palette block.
 *
 * Run this whenever lib/theme-palettes.ts changes; commit the generated
 * file so no build-time step is required.
 */
import { writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { PALETTE_DEFS, THEME_TOKENS } from "../lib/theme-palettes.ts";

const __dirname = dirname(fileURLToPath(import.meta.url));
const outPath = resolve(__dirname, "..", "app", "palettes.css");

const order = Object.keys(PALETTE_DEFS);

function block(selector, tokens) {
  const body = THEME_TOKENS.map((t) => `  --${t}: ${tokens[t]};`).join("\n");
  return `${selector} {\n${body}\n}`;
}

const parts = [];
parts.push(`/* Generated by scripts/generate-palette-css.mjs — do not edit by hand.`);
parts.push(` * Source of truth: lib/theme-palettes.ts. */\n`);

for (const id of order) {
  if (id === "pi") continue; // pi is the default (no data-palette attribute)
  const def = PALETTE_DEFS[id];
  parts.push(`/* --- ${def.label} --- */`);
  parts.push(block(`html[data-palette="${id}"]`, def.tokens.dark));
  parts.push("");
  parts.push(block(`html:not(.dark)[data-palette="${id}"]`, def.tokens.light));
  parts.push("");
}

await writeFile(outPath, parts.join("\n"), "utf-8");

console.log(`Wrote ${outPath}`);
console.log(`  palettes: ${order.length} (${order.length - 1} with data-palette blocks)`);
console.log(`  tokens per block: ${THEME_TOKENS.length}`);
